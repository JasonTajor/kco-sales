const preamble = parts[0]!.lines.join('\n')

/**
 * A part, ready to paste.
 *
 * Wrapped in its own transaction so a failure rolls back only that part, and
 * carrying the preamble header so a file opened on its own still says what it
 * is and how to regenerate it. The verification part is not wrapped - it only
 * reads.
 */
function render(p: Part, index: number, total: number): string {
  const header = `${preamble}
-- ---------------------------------------------------------------------------
-- PART ${index} OF ${total}: ${p.title}
--
-- Run the parts in filename order. Each is idempotent on its own, so a part
-- can be re-run safely; running them out of order will fail on a foreign key.
-- ---------------------------------------------------------------------------
`
  const body = p.lines.join('\n')
  const readOnly = p.slug === '99-verify'

  return readOnly ? `${header}\n${body}\n` : `${header}\nbegin;\n${body}\ncommit;\n`
}

const outDirArg = process.argv.indexOf('--out-dir')

if (outDirArg !== -1) {
  const dir = process.argv[outDirArg + 1]
  if (!dir) throw new Error('--out-dir needs a path')

  const content = parts.slice(1)
  mkdirSync(dir, { recursive: true })

  const written = content.map((p, i) => {
    const file = join(dir, `${p.slug}.sql`)
    const sql = render(p, i + 1, content.length)
    writeFileSync(file, sql)
    return { file, bytes: Buffer.byteLength(sql), lines: sql.split('\n').length }
  })

  // A manifest, so it is obvious what to paste and in what order.
  const manifest = [
    '# Seed parts',
    '',
    'GENERATED by supabase/seed/generate.ts - do not edit.',
    'Regenerate with `./scripts/seed.sh`.',
    '',
    'The full seed is too large for the Supabase SQL Editor to save as one',
    'snippet, so it is emitted in parts. Paste and run them in this order:',
    '',
    '| # | File | Size |',
    '| - | ---- | ---- |',
    ...written.map(
      (w, i) => `| ${i + 1} | \`${w.file.split('/').pop()}\` | ${Math.ceil(w.bytes / 1024)} kB |`,
    ),
    '',
    'Every part is idempotent, so re-running one is safe. Running them out of',
    'order will fail on a foreign key rather than corrupt anything.',
    '',
  ].join('\n')
  writeFileSync(join(dir, 'README.md'), manifest)

  written.forEach((w) => {
    process.stderr.write(`  ${w.file}  ${String(Math.ceil(w.bytes / 1024)).padStart(4)} kB\n`)
  })
  process.stderr.write(`  ${join(dir, 'README.md')}\n`)
} else {
  // Single-file output, for psql and the verification scripts.
  const all = parts
    .slice(1)
    .map((p) => p.lines.join('\n'))
    .join('\n')
  process.stdout.write(`${preamble}\nbegin;\n${all}\ncommit;\n`)
}
