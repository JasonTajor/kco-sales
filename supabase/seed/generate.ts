/* ------------------------------------------------------------------ ids ---- */

const catId = (slug: string) => stableUuid(`category:${slug}`)
const modId = (slug: string) => stableUuid(`module:${slug}`)
const lessonId = (modSlug: string, index: number) => stableUuid(`lesson:${modSlug}:${index}`)
const blockId = (modSlug: string, li: number, bi: number) =>
  stableUuid(`block:${modSlug}:${li}:${bi}`)
const pathId = (slug: string) => stableUuid(`path:${slug}`)
const assessId = (slug: string) => stableUuid(`assessment:${slug}`)
const questionId = (aSlug: string, i: number) => stableUuid(`question:${aSlug}:${i}`)
const choiceId = (aSlug: string, qi: number, ci: number) =>
  stableUuid(`choice:${aSlug}:${qi}:${ci}`)

/** src/data references categories by their local id, e.g. 'cat-phone'. */
const catSlugByLocalId = new Map(categories.map((c) => [c.id, c.slug]))
/** ...and materials by 'mat-phone-etiquette'. */
const matSlugByLocalId = new Map(materials.map((m) => [m.id, m.slug]))

/**
 * Output is collected into named parts.
 *
 * The whole seed is 228 kB, which the Supabase SQL Editor refuses to save as a
 * snippet. Emitting it as several files that each stand on their own means it
 * can be pasted in pieces - and because every part is its own transaction, a
 * failure part-way leaves the earlier parts applied rather than needing the
 * lot re-run.
 *
 * Parts must stay in order: a module references a category, a lesson a module,
 * a path item a module. The numbering in the filename is that order.
 */
interface Part {
  slug: string
  title: string
  lines: string[]
}

const parts: Part[] = []
let current: Part = { slug: '00-preamble', title: 'Preamble', lines: [] }
parts.push(current)

const w = (s: string) => current.lines.push(s)

/** Opens a new part. Everything written after this lands in it. */
function part(slug: string, title: string): void {
  current = { slug, title, lines: [] }
  parts.push(current)
  w(banner(title))
}

