/**
 * The script library (§24) is DERIVED, not authored separately.
 *
 * Scripts already exist in the source material as `script` blocks inside
 * lessons and quick-reference cards. Extracting them into their own table
 * makes them searchable, copyable and admin-editable as §24 requires, without
 * creating a second copy of the same words that could drift from the lesson
 * it came from. `source_ref` in the notes records where each one came from.
 */
interface DerivedScript {
  slug: string
  title: string
  kind: 'phone' | 'chat' | 'closing' | 'qualification' | 'follow-up' | 'complaint' | 'wording'
  channel: 'phone' | 'chat' | 'both'
  situation: string
  language: 'en' | 'fil' | 'mixed'
  lines: string[]
  notes: string
  tags: string[]
}

/** Classifies a script by the words in its label and the context it sits in. */
function classify(label: string, context: string): { kind: DerivedScript['kind']; channel: DerivedScript['channel'] } {
  const h = `${label} ${context}`.toLowerCase()
  if (/complaint|angry|damaged|refund|escalat/.test(h)) return { kind: 'complaint', channel: 'both' }
  if (/clos|order|confirm|reserve/.test(h)) return { kind: 'closing', channel: 'both' }
  if (/follow.?up|seen|reply|balik/.test(h)) return { kind: 'follow-up', channel: 'both' }
  if (/qualif|discover|question|need/.test(h)) return { kind: 'qualification', channel: 'both' }
  if (/chat|messenger|message/.test(h)) return { kind: 'chat', channel: 'chat' }
  if (/phone|call|hold|ring/.test(h)) return { kind: 'phone', channel: 'phone' }
  return { kind: 'phone', channel: 'both' }
}

const derived: DerivedScript[] = []
const seenScriptSlugs = new Set<string>()

function addScript(
  labelRaw: string,
  context: string,
  language: 'en' | 'fil' | 'mixed',
  lines: string[],
  source: string,
  tags: string[],
) {
  const label = labelRaw.trim() || 'Script'
  const base = `${context}-${label}`
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, 60)

  // Two lessons can carry a script under the same label; keep both, since the
  // wording differs, but give them distinct slugs.
  let slug = base
  let n = 2
  while (seenScriptSlugs.has(slug)) slug = `${base}-${n++}`
  seenScriptSlugs.add(slug)

  const { kind, channel } = classify(label, context)
  derived.push({
    slug,
    title: label,
    kind,
    channel,
    situation: context,
    language,
    lines,
    notes: `Source: ${source}`,
    tags,
  })
}

materials.forEach((m) => {
  m.sections.forEach((s) => {
    s.blocks.forEach((b) => {
      if (b.type !== 'script') return
      addScript(b.label ?? s.title, s.title, b.language, b.lines, `${m.title} - ${s.title}`, m.tags)
    })
  })
})

quickReferenceCards.forEach((c) => {
  c.blocks.forEach((b) => {
    if (b.type !== 'script') return
    addScript(b.label ?? c.title, c.title, b.language, b.lines, `Quick Reference - ${c.title}`, [c.kind])
  })
})

