/**
 * Seed generator (§42).
 *
 * Reads the authored content in `src/data` - which is where the source
 * training documents were transcribed - and emits one idempotent SQL script.
 *
 *   ./scripts/seed.sh            # writes supabase/seed/seed.sql
 *
 * Design rules this follows:
 *
 *  - **Deterministic ids.** Every row's uuid is hashed from a stable natural
 *    key, so re-running produces the same ids and `on conflict do update`
 *    updates rather than duplicating (§42, §68).
 *
 *  - **No invented business data.** Nothing is synthesised here. The only rows
 *    this file creates that are not in src/data are the Sales Bible slots and
 *    the competency framework, and those are written with `value = null`,
 *    which is what the UI reads as "Admin content required" (§78, §43).
 *
 *  - **Content only.** No users, no progress, no assessment attempts. Those
 *    belong to real people using the system; seeding them would be the fake
 *    data §71 rules out.
 */

