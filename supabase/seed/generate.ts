function isTrueFalse(options: string[]): boolean {
  if (options.length !== 2) return false
  const set = options.map((o) => o.trim().toLowerCase()).sort()
  return (
    (set[0] === 'false' && set[1] === 'true') ||
    (set[0] === 'hindi' && set[1] === 'oo') ||
    (set[0] === 'mali' && set[1] === 'tama')
  )
}

